-- Additive upgrade: preserve existing player, match, wallet and review records.
create table if not exists game_runtime.team_messages (
  seq bigint generated by default as identity primary key,
  id text unique not null,
  squad_id text not null,
  player_id text not null,
  client_id text not null,
  name text not null,
  text text not null check (char_length(text) between 1 and 500),
  at bigint not null,
  unique(squad_id,player_id,client_id)
);
create index if not exists team_message_history on game_runtime.team_messages(squad_id,seq);
create index if not exists team_message_rate on game_runtime.team_messages(player_id,at desc);
alter table game_runtime.team_messages enable row level security;
-- Chat authorization belongs to the game server; browser roles cannot read this table.
revoke all on game_runtime.team_messages from public, anon, authenticated;
revoke all on sequence game_runtime.team_messages_seq_seq from public, anon, authenticated;
